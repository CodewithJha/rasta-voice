"""Prisma speech-to-text.

Live REST: POST {base}/stt/v3  (multipart, header X-API-Key-ID).
The path version ``v3`` is the API version, not the model. Send
``model=prisma-v3.0`` or omit it for Prisma v2.5.

Realtime audio is WebSocket ``{ws_base}/stt/v3/stream`` with the headers
from :func:`stream_headers`. PCM is 16-bit mono, 1024-byte frames.
This module builds those headers. The socket loop lands in a later issue
so the benchmark and the app do not edit this file to add streaming.

Denoise is not a REST field. It is ``with_denoise`` on the batch job
config (see :mod:`gnani_client.batch`).
"""

from __future__ import annotations

import json
from contextlib import nullcontext
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import httpx

from gnani_client.env import base_url, require_api_key, ws_base
from gnani_client.errors import GnaniError, error_message

RIDER_KEYTERMS = ["order", "gate", "customer", "item", "accident", "traffic"]
RIDER_TOPIC = (
    "A delivery rider on a noisy city phone line speaks Hinglish about one "
    "live order: a closed gate, a customer who does not pick up, a missing "
    "item, a traffic delay, or an accident."
)

# Docs: telephony wants a higher VAD bar than a clean laptop mic.
TELEPHONY_VAD = {
    "x-sample-rate": "8000",
    "x-vad-threshold": "0.7",
    "x-min-silence-ms": "500",
    "x-min-speech-ms": "200",
    "x-min-segment-ms": "200",
}


@dataclass(frozen=True)
class SttResult:
    transcript: str
    model: str
    request_id: str | None
    detected_language_code: str | None
    success: bool
    processing_time: float | None = None


def stream_headers(
    *,
    api_key: str,
    model: str = "prisma-v3.0",
    language_code: str = "hi-IN,en-IN",
    sample_rate: int = 16000,
    output_format: str = "codemix",
    keyterms: list[str] | None = None,
    topic: str | None = None,
    idle_timeout_sec: int = 60,
    preset: str | None = None,
) -> dict[str, str]:
    """WebSocket upgrade headers for ``/stt/v3/stream``.

    ``preset="telephony"`` pins 8 kHz and the noisy-line VAD knobs from the
    Prisma realtime docs. Reconnect to change them; they are fixed per socket.
    """
    rate = 8000 if preset == "telephony" else sample_rate
    headers = {
        "x-api-key-id": api_key,
        "model": model,
        "language_code": language_code,
        "x-sample-rate": str(rate),
        "format": output_format,
        "x-idle-timeout-sec": str(idle_timeout_sec),
    }
    if preset == "telephony":
        headers.update(TELEPHONY_VAD)
    if keyterms:
        headers["keyterms"] = json.dumps(keyterms, ensure_ascii=False)
    if topic:
        headers["topic"] = topic
    return headers


class PrismaSTT:
    def __init__(
        self,
        key: str | None = None,
        *,
        base: str | None = None,
        client: httpx.Client | None = None,
    ):
        self.api_key = require_api_key(key)
        self.base = (base or base_url()).rstrip("/")
        self._client = client

    @property
    def stream_url(self) -> str:
        return f"{ws_base(self.base)}/stt/v3/stream"

    def transcribe(
        self,
        audio: bytes,
        *,
        filename: str = "clip.wav",
        model: str = "prisma-v3.0",
        language_code: str = "hi-IN,en-IN",
        output_format: str | None = "codemix",
        keyterms: list[str] | None = None,
        topic: str | None = None,
    ) -> SttResult:
        safe_name = Path(filename).name or "clip.wav"
        form: dict[str, str] = {"model": model, "language_code": language_code}
        if output_format:
            form["format"] = output_format
        if keyterms:
            form["keyterms"] = json.dumps(keyterms, ensure_ascii=False)
        if topic:
            form["topic"] = topic
        files = {"audio_file": (safe_name, audio, _mime(safe_name))}
        with self._http() as http:
            response = http.post(
                f"{self.base}/stt/v3",
                headers={"X-API-Key-ID": self.api_key},
                data=form,
                files=files,
            )
        return _parse_stt(response, model)

    def _http(self):
        if self._client is not None:
            return nullcontext(self._client)
        return httpx.Client(timeout=60.0)


def _mime(filename: str) -> str:
    ext = Path(filename).suffix.lower()
    return {
        ".wav": "audio/wav",
        ".mp3": "audio/mpeg",
        ".ogg": "audio/ogg",
        ".flac": "audio/flac",
        ".aac": "audio/aac",
        ".m4a": "audio/mp4",
    }.get(ext, "application/octet-stream")


def _parse_stt(response: httpx.Response, requested_model: str) -> SttResult:
    text = response.text
    try:
        body: dict[str, Any] = response.json()
    except json.JSONDecodeError as exc:
        raise GnaniError(
            f"STT returned non-JSON ({response.status_code})",
            status=response.status_code,
            body=text[:500],
        ) from exc
    if response.status_code != 200 or not body.get("success"):
        message = error_message(text, f"STT failed ({response.status_code})")
        raise GnaniError(
            f"Prisma STT {response.status_code}: {message}",
            status=response.status_code,
            body=text[:500],
        )
    return SttResult(
        transcript=str(body.get("transcript") or ""),
        model=str(body.get("model") or requested_model),
        request_id=body.get("request_id"),
        detected_language_code=body.get("detected_language_code"),
        success=True,
        processing_time=body.get("processing_time"),
    )
